#!/usr/bin/env node
/**
 * extract_base.js
 * Reads the frozen v41 single-file app and writes hub/data/base.js:
 * the agent catalogue, the 62 team presets (nodes + edges) and the small
 * lookup tables the observatory needs. Read-only on v41; safe to re-run.
 *
 * Usage: node hub/tools/extract_base.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(ROOT, 'v41', 'AGENT_TEAMS_CONFIGURATOR_v41.html');
const OUT = path.join(__dirname, '..', 'data', 'base.js');
const html = fs.readFileSync(SRC, 'utf-8');

function scan(src, start, open, close) {
  let depth = 0, inS = false, sc = '';
  for (let i = start; i < src.length; i++) {
    const ch = src[i], nx = src[i + 1];
    if (!inS && ch === '/' && nx === '/') { while (i < src.length && src[i] !== '\n') i++; continue; }
    if (!inS && ch === '/' && nx === '*') { i = src.indexOf('*/', i + 2) + 1; continue; }
    if (inS) { if (ch === '\\') { i++; continue; } if (ch === sc) inS = false; continue; }
    if (ch === "'" || ch === '"' || ch === '`') { inS = true; sc = ch; continue; }
    if (ch === open) depth++;
    if (ch === close) { depth--; if (depth === 0) return i; }
  }
  return -1;
}

function extract(name) {
  const re = new RegExp('(const|let|var)\\s+' + name + '\\s*=\\s*([\\[{])');
  const m = re.exec(html);
  if (!m) throw new Error('not found: ' + name);
  const open = m[2], close = open === '[' ? ']' : '}';
  const s = m.index + m[0].length - 1;
  const e = scan(html, s, open, close);
  return new Function('return ' + html.substring(s, e + 1))();
}

function extractAD() {
  let agents = extract('AD');
  let i = html.indexOf('AD.push(');
  while (i !== -1) {
    const p = i + 'AD.push('.length - 1;
    const e = scan(html, p, '(', ')');
    const inner = html.substring(p + 1, e).trim();
    if (inner.startsWith('{')) {
      try { agents = agents.concat(new Function('return [' + inner + ']')()); } catch (err) { /* runtime push */ }
    }
    i = html.indexOf('AD.push(', i + 1);
  }
  return agents;
}

const AD = extractAD();
const PR = extract('PR');
const PC = extract('PC');
const PM = extract('PM');
const PHASES = extract('PHASES');
const PRESET_CATEGORIES = extract('PRESET_CATEGORIES');
const CATEGORY_META = extract('CATEGORY_META');
const AG_CAT_META = extract('AG_CAT_META');
const MODEL_META = extract('MODEL_META');
const PCAT = extract('PCAT');
const I18N = extract('I18N_EN');

// strip html tags and collapse whitespace; keep the full text — the v41 role
// descriptions carry constraints the observatory detail views should not lose
const cleanText = (s) => {
  if (!s) return '';
  return String(s).replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
};

const agents = {};
AD.forEach((a) => {
  agents[a.id] = {
    id: a.id,
    nameEn: (I18N.agentNames && I18N.agentNames[a.id]) || a.name,
    cat: a.cat,
    phase: a.phase || 'build',
    model: a.model,
    roleEn: cleanText((I18N.agentDescs && I18N.agentDescs[a.id]) || a.role),
    tools: a.tools || '',
  };
});

const presets = {};
Object.keys(PR).forEach((id) => {
  const pm = PM[id] || {};
  presets[id] = {
    id,
    nameEn: (I18N.presetNames && I18N.presetNames[id]) || pm.n || id,
    count: pm.c || PR[id].length,
    descEn: (I18N.presetDescs && I18N.presetDescs[id]) || pm.dsc || '',
    useEn: (I18N.presetUse && I18N.presetUse[id]) || pm.use || '',
    flow: pm.pt || '',
    tokens: pm.t || '',
    cost: pm.$ || '',
    category: PRESET_CATEGORIES[id] || 'build',
    nodes: PR[id].map((n) => ({ d: n.d, x: n.x, y: n.y, m: n.m || null })),
    edges: (PC[id] || []).map((e) => [e[0], e[1], e[2]]),
  };
});

const presetCats = {};
Object.keys(CATEGORY_META).forEach((k) => {
  presetCats[k] = { id: k, zh: CATEGORY_META[k].en || k, color: CATEGORY_META[k].cl || '#666' };
});
const agentCats = {};
Object.keys(AG_CAT_META).forEach((k) => {
  agentCats[k] = { id: k, zh: AG_CAT_META[k].en || k, color: AG_CAT_META[k].c || '#666' };
});

const base = {
  source: 'v41/AGENT_TEAMS_CONFIGURATOR_v41.html',
  agents,
  presets,
  phases: PHASES.map((p) => ({ id: p.id, color: p.color })),
  presetCats,
  agentCats,
  sizeGroups: PCAT.map((g) => ({ ids: g.ids })),
  models: MODEL_META.map((m) => ({ k: m.k, label: m.label, short: m.short, ctx: m.ctx })),
};

const banner = '/* Generated by hub/tools/extract_base.js from ' + base.source + '. Do not hand-edit. */\n';
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, banner + 'window.HUB = window.HUB || {};\nHUB.base = ' + JSON.stringify(base, null, 1) + ';\n', 'utf-8');
console.log('agents', Object.keys(agents).length, 'presets', Object.keys(presets).length, '->', path.relative(ROOT, OUT));
