// Builds hub/data/capabilities.json — the capability registry — from channels/probe/blackboard.jsonl.
// Never edit the JSON by hand; re-run: node channels/probe/scripts/build_capabilities.js
//
// For each family it records:
//   routes:  every tested route → capability → { state, line } (latest blackboard record)
//   gateway: what our gateway can do for that family, per capability. Taken from the gateway's own
//            L2 record when one exists; otherwise from the lower route the gateway actually calls
//            (acpx L1b for six families, agentapi L0 for Antigravity); otherwise "unverified".
const fs = require('fs');
const path = require('path');
const { CAPS, readRows, latestByCell } = require('./blackboard_lib');

const OUT = path.resolve(__dirname, '..', '..', '..', 'hub', 'data', 'capabilities.json');
const STATES = { pass: 'pass', fail: 'fail', partial: 'partial', 'n/a': 'n/a', unverified: 'unverified' };
// The lower route our gateway calls for each family (trace/apps/cli/src/gateway.ts).
const GATEWAY_CALLS = {
  antigravity: 'antigravity/L0/agentapi',
};

const { rows } = readRows();
const latest = latestByCell(rows);
const families = [...new Set(rows.map((r) => r.family))].filter((f) => f && f !== '*').sort();

const out = {
  generatedAt: new Date().toISOString(),
  source: 'channels/probe/blackboard.jsonl',
  note: 'Generated by channels/probe/scripts/build_capabilities.js. state: pass / partial / fail / n/a / unverified. line: blackboard line number of the evidence.',
  families: {},
};

for (const fam of families) {
  const famRows = rows.filter((r) => r.family === fam);
  const routes = {};
  for (const r of famRows) {
    const cell = latest.get(`${fam}|${r.route}|${r.capability}`);
    if (!cell || !r.capability) continue;
    routes[r.route] = routes[r.route] || { layer: r.layer, surface: r.surface || null, caps: {} };
    routes[r.route].caps[r.capability] = { state: STATES[cell.result] || 'unverified', line: cell._line };
  }
  const l2 = routes[`${fam}/L2/server-api`];
  const calledRoute =
    GATEWAY_CALLS[fam] || Object.keys(routes).find((k) => k.startsWith(`${fam}/L1b/`)) || null;
  const gateway = {};
  for (const cap of CAPS) {
    const fromL2 = l2 && l2.caps[cap];
    const fromLower = calledRoute && routes[calledRoute] && routes[calledRoute].caps[cap];
    gateway[cap] = fromL2
      ? { ...fromL2, via: `${fam}/L2/server-api` }
      : fromLower
      ? { ...fromLower, via: calledRoute }
      : { state: 'unverified', line: null, via: null };
  }
  out.families[fam] = { gatewayCalls: calledRoute, gateway, routes };
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n', 'utf8');
const summary = families
  .map((f) => {
    const g = out.families[f].gateway;
    const n = (s) => CAPS.filter((c) => g[c].state === s).length;
    return `${f}: pass ${n('pass')} / partial ${n('partial')} / fail ${n('fail')} / unverified ${n('unverified')}`;
  })
  .join('\n');
console.log(`${path.relative(process.cwd(), OUT)}\n${summary}`);
